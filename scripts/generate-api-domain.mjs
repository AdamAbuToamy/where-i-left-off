import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
const require = createRequire(
  new URL("../push-worker/package.json", import.meta.url),
);
const { build } = require("esbuild");
const result = await build({
  stdin: {
    contents: `export {planAssistantChanges,blankAssistantData} from './src/assistant/actions'; export {parsePlanBackup} from './src/university/planImport'; export {parsePlanningState} from './src/planning/domain'; export {ProjectEntity} from './src/lib/projectEntity';`,
    resolveDir: fileURLToPath(new URL("..", import.meta.url)),
  },
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2024",
  resolveExtensions: [".ts", ".js", ".mjs", ".tsx", ".json"],
  write: false,
  legalComments: "none",
  banner: {
    js: "// Generated by scripts/generate-api-domain.mjs from existing Wilo domain. Do not edit.",
  },
});
const file = new URL("../shared/wiloApiDomain.mjs", import.meta.url),
  text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if ((await readFile(file, "utf8")) !== text)
    throw Error("API domain bundle is stale");
} else await writeFile(file, text);
