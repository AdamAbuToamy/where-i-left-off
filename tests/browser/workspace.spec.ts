  await login(page, ownerEmail, true)
  await add(page, 'Private owner note')
  await page.locator('.side-navigation-toggle').press('Enter');await page.getByRole('link', { name: 'Groups', exact: true }).click()
  await page.locator('.group-create summary').filter({ hasText: 'Create group' }).click()
