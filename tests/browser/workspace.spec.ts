test('renders untrusted card text as text and preserves mobile account layout in three languages', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, `markup-${Date.now()}@example.test`, true)
  const payload = '<img src=x onerror="window.injected=true">'
  await add(page, payload)
  await expect(page.locator('article img')).toHaveCount(0)
  expect(await page.evaluate(() => 'injected' in window)).toBe(false)
  for (const [language, label] of [['ar', 'العربية'], ['he', 'עברית'], ['en', 'English']]) {
    await page.locator('.language-picker button').first().click()
    await page.locator('.language-option').filter({ hasText: label }).click()
    await expect(page.locator('html')).toHaveAttribute('lang', language)
    const sizes = await page.locator('.account-strip').evaluate(el => ({
      overflow: document.documentElement.scrollWidth > innerWidth,
      status: el.querySelector('.sync-status')!.getBoundingClientRect().width,
      clipped: el.querySelector('.sync-status')!.scrollWidth > el.querySelector('.sync-status')!.clientWidth + 1,
    }))
    expect(sizes.overflow).toBe(false)
    expect(sizes.status).toBeGreaterThan(40)
    expect(sizes.status).toBeLessThan(220)
    expect(sizes.clipped).toBe(false)
  }
})


