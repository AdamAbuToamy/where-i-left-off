import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'

async function visit(page: Page) {
  await page.addInitScript(() => {
    localStorage.setItem('language', 'en')
    Object.defineProperty(crypto, 'randomUUID', { value: undefined, configurable: true })
  })
  await page.goto('/')
}
async function login(page: Page, email: string, register = false) {
  await visit(page)
  if (register) await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Test-Password-2026')
  await page.locator('form').getByRole('button', { name: register ? 'Create account' : 'Sign in', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
}
async function add(page: Page, name: string) {
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill(name)
  await page.getByLabel('Next step', { exact: true }).fill('Continue tomorrow')
  await page.getByRole('button', { name: 'Add project', exact: true }).click()
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  await expect(page.locator('.sync-status')).toHaveText('Synced with your account')
}

test('phone creation, two sessions, persistence, edits, ordering, isolation and custom delete', async ({ browser, page }) => {
  const phoneContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const phone = await phoneContext.newPage()
  const email = `owner-${Date.now()}@example.test`
  await login(phone, email, true)
  await login(page, email)
  await add(phone, 'Robot arm')
  await expect(page.getByRole('heading', { name: 'Robot arm', exact: true })).toBeVisible()
  await add(page, 'STOMP')
  await expect(phone.getByRole('heading', { name: 'STOMP', exact: true })).toBeVisible()
  const robot = page.locator('article').filter({ has: page.getByRole('heading', { name: 'Robot arm', exact: true }) })
  await robot.getByRole('button', { name: 'Edit', exact: true }).click()
  await page.locator('.card-editor').getByLabel('Next step', { exact: true }).fill('Fit the bearing')
  await page.locator('.card-editor').getByRole('button', { name: 'Save changes', exact: true }).click()
  await expect(phone.getByText('Fit the bearing', { exact: true })).toBeVisible()
  await robot.getByRole('button', { name: 'Start project', exact: true }).click()
  await expect(phone.locator('article.is-active h2')).toHaveText('Robot arm')
  await page.mouse.move(0, 0)
  await expect(robot.getByRole('button', { name: 'Postpone project' })).toHaveCSS('background-color', 'rgb(170, 76, 42)')
  // Keyboard sensor exercises the same saved reorder callback used by mouse/touch.
  const handle = phone.getByRole('button', { name: 'Drag to reorder: STOMP', exact: true })
  await handle.focus()
  await phone.keyboard.press('Space')
  await expect(phone.locator('.is-dragging')).toHaveCount(1)
  await phone.keyboard.press('ArrowUp')
  await expect(phone.locator('[role="status"]').filter({ hasText: 'STOMP. Position: 1' })).toHaveCount(1)
  await phone.keyboard.press('Space')
  await expect(phone.locator('article h2').first()).toHaveText('STOMP')
  await expect(page.locator('article h2').first()).toHaveText('STOMP')
  await phone.reload()
  await expect(phone.locator('article h2').first()).toHaveText('STOMP')
  await expect(phone.getByText('Fit the bearing', { exact: true })).toBeVisible()
  await robot.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(robot).toBeVisible()
  await robot.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(phone.getByRole('heading', { name: 'Robot arm', exact: true })).toHaveCount(0)
  const strangerContext = await browser.newContext()
  const strangerPage = await strangerContext.newPage()
  await login(strangerPage, `stranger-${Date.now()}@example.test`, true)
  await expect(strangerPage.locator('article')).toHaveCount(0)
  await strangerContext.close()
  await phoneContext.close()
})

test('three languages, retained drafts, search, offline controls and no horizontal overflow', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await login(page, `language-${Date.now()}@example.test`, true)
  await add(page, 'Camera')
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name', { exact: true }).fill('Keep my draft')
  await page.locator('.language-trigger').click()
  await page.locator('.language-option').filter({ hasText: 'العربية' }).click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await expect(page.locator('#project-name')).toHaveValue('Keep my draft')
  await page.locator('.language-trigger').click()
  await page.locator('.language-option').filter({ hasText: 'עברית' }).click()
  await expect(page.locator('html')).toHaveAttribute('lang', 'he')
  await expect(page.locator('#project-name')).toHaveValue('Keep my draft')
  await page.locator('.language-trigger').click()
  await page.locator('.language-option').filter({ hasText: 'English' }).click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr')
  await page.getByRole('searchbox').fill('unmatched')
  await expect(page.getByText('No matching projects.')).toBeVisible()
  await page.getByRole('searchbox').fill('Camera')
  await expect(page.getByRole('heading', { name: 'Camera', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await context.setOffline(true)
  await expect(page.locator('.sync-status')).toContainText('offline')
  await expect(page.getByRole('button', { name: 'Add project', exact: true })).toBeDisabled()
  await context.setOffline(false)
})
