async function visit(page: Page) {
  await page.addInitScript(() => {
    localStorage.setItem('language', 'en')
    Object.defineProperty(crypto, 'randomUUID', { value: undefined, configurable: true })
  })
  await page.goto('/')
}
async function login(page: Page, email: string, register = false) {
  await visit(page)
  if (register) await page.getByRole('button', { name: 'Create account', exact: true }).click()
  if (register) await page.getByLabel('Personal name', { exact: true }).fill(email.split('@')[0])
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Password', { exact: true }).fill('Test-Password-2026')
  await page.locator('form').getByRole('button', { name: register ? 'Create account' : 'Sign in', exact: true }).click()
  await expect(page.locator('.side-navigation-toggle')).toBeVisible()
  const tour = page.locator('.welcome-guide .guide-skip')
  if (await tour.isVisible()) await tour.click()
  await expect(page.locator('.welcome-guide')).toHaveCount(0)
}
async function add(page: Page, name: string, details: { projectUrl?: string; attachmentUrl?: string; dueDate?: string } = {}) {
  await page.getByRole('button', { name: 'New card', exact: true }).click()
  await page.locator('.form-reveal').evaluate(async element => {
    await Promise.all(element.getAnimations({ subtree: true }).filter(a => a.effect?.getComputedTiming().iterations !== Infinity).map(a => a.finished.catch(() => {})))
  })
  await page.getByLabel('Card title', { exact: true }).fill(name)
  await page.getByLabel('Next step', { exact: true }).fill('Continue tomorrow')
  if (details.projectUrl) await page.getByLabel('Project link', { exact: true }).fill(details.projectUrl)
  if (details.attachmentUrl) await page.getByLabel('File or image link', { exact: true }).fill(details.attachmentUrl)
  if (details.dueDate) await page.getByLabel('Follow-up date', { exact: true }).fill(details.dueDate)
  await page.getByRole('button', { name: 'Save card', exact: true }).click()
  try {
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible()
  } catch (error) {
    await test.info().attach('card-save-state', { body: JSON.stringify(await page.evaluate(() => ({
      alert: document.querySelector('[role="alert"]')?.textContent,
      form: document.querySelector('.new-project-form')?.textContent,
      fields: [...document.querySelectorAll<HTMLInputElement>('.new-project-form input, .new-project-form textarea, .new-project-form select')].map(e => ({ id: e.id, value: e.value, valid: e.validity.valid, message: e.validationMessage })),
    })), null, 2), contentType: 'application/json' })
    throw error
  }
  await expect(page.locator('.sync-status')).toHaveText('Synced with your account', { timeout: 15000 })
}

